#!/usr/bin/env python3
"""install.sh smoke tests — backlog item 23.

Two layers:

1. Static — `bash -n` syntax check plus optional shellcheck lint. The
   shellcheck test is skipped (not failed) when shellcheck is not
   available on PATH so this suite stays runnable on fresh machines.

2. Rehearsal — run install.sh against a file://-backed local source
   (via the AXIOM_REPO_BASE env var added in the same commit) into a
   tempdir, then assert that (a) every expected skill file was
   installed, (b) .claude/settings.json gained a PreToolUse entry
   pointing at the hook, and (c) `.axiom/invariants.yaml` was
   auto-generated by axiom_init.

The rehearsal exercises the happy path end-to-end without touching
the network or the user's $HOME; failure-path coverage (bad tag,
partial curl) is a follow-up.
"""

import json
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile
import unittest

REPO_ROOT = pathlib.Path(__file__).parent.parent
INSTALL_SH = REPO_ROOT / "install.sh"
SKILL_SRC = REPO_ROOT / ".claude" / "skills" / "axiom-csc"


class InstallStaticTests(unittest.TestCase):

    def test_install_sh_bash_syntax_ok(self):
        result = subprocess.run(
            ["bash", "-n", str(INSTALL_SH)], capture_output=True, text=True
        )
        self.assertEqual(
            result.returncode,
            0,
            f"bash -n must pass; stderr={result.stderr!r}",
        )

    def test_install_sh_uses_strict_mode(self):
        text = INSTALL_SH.read_text()
        self.assertIn(
            "set -euo pipefail",
            text,
            "install.sh must use strict mode (set -euo pipefail)",
        )

    def test_install_sh_wraps_curl_in_fetch_helper(self):
        """Regression against the pre-0c93bf0 raw-curl loop: every skill
        download must go through fetch() so a mid-fail prints a hint and
        aborts cleanly."""
        text = INSTALL_SH.read_text()
        self.assertIn("fetch() {", text, "fetch() helper missing")
        # Count bare `curl -fsSL "$REPO_BASE/` outside the function body.
        # Any such line is a regression — fetch() is the sanctioned form.
        bad = [
            line
            for line in text.splitlines()
            if 'curl -fsSL "$REPO_BASE/' in line and "fetch" not in line
        ]
        self.assertFalse(
            bad, f"skill downloads must use fetch(); offenders: {bad}"
        )

    @unittest.skipUnless(shutil.which("shellcheck"), "shellcheck not installed")
    def test_shellcheck_passes(self):
        result = subprocess.run(
            ["shellcheck", "-x", str(INSTALL_SH)],
            capture_output=True,
            text=True,
        )
        # Allow SC2155 (declare-and-assign) and SC2129 (multiple redirects),
        # which are stylistic and already prevalent in the existing script.
        # Fail on everything else.
        if result.returncode != 0:
            # Re-run with specific excludes to confirm the remaining issues
            # are real bugs, not just style.
            narrow = subprocess.run(
                ["shellcheck", "-x", "-e", "SC2155,SC2129", str(INSTALL_SH)],
                capture_output=True,
                text=True,
            )
            self.assertEqual(
                narrow.returncode,
                0,
                f"shellcheck found real issues (excluding SC2155/SC2129):\n{narrow.stdout}",
            )


class InstallRehearsalTests(unittest.TestCase):
    """Run install.sh against a file://-backed local source."""

    @classmethod
    def setUpClass(cls):
        cls.tmp = pathlib.Path(tempfile.mkdtemp(prefix="axiom-install-"))
        cls.project = cls.tmp / "fake-project"
        cls.project.mkdir()
        # Mark it as a project root so install.sh doesn't warn/prompt.
        (cls.project / "package.json").write_text("{}")
        # Expose the skill directory as the install source via file://.
        cls.file_base = f"file://{SKILL_SRC}"

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.tmp, ignore_errors=True)

    def _run_install(self):
        env = {
            **os.environ,
            "AXIOM_REPO_BASE": self.file_base,
            # Keep the user's real ~/.config untouched — point the telemetry
            # consent check at a throwaway dir by overriding HOME, since
            # install.sh writes consent to $HOME/.config/axiom-csc/.
            "HOME": str(self.tmp / "fake-home"),
        }
        (self.tmp / "fake-home").mkdir(exist_ok=True)
        # Non-TTY stdin so the install skips interactive prompts.
        return subprocess.run(
            ["bash", str(INSTALL_SH)],
            cwd=str(self.project),
            env=env,
            input="",
            capture_output=True,
            text=True,
            timeout=30,
        )

    def test_install_completes_successfully(self):
        result = self._run_install()
        self.assertEqual(
            result.returncode,
            0,
            f"install.sh failed:\nstdout={result.stdout}\nstderr={result.stderr}",
        )

    def test_install_writes_all_skill_files(self):
        self._run_install()
        skill_dir = self.project / ".claude" / "skills" / "axiom-csc"
        expected = [
            "SKILL.md",
            "hooks/pre_tool_use.py",
            "scripts/lower_ast.py",
            "scripts/eval_lemma.py",
            "scripts/axiom_init.py",
            "scripts/axiom.py",
            "scripts/axiom_flush.py",
            "references/INVARIANTS_SPEC.md",
        ]
        missing = [p for p in expected if not (skill_dir / p).is_file()]
        self.assertFalse(missing, f"missing after install: {missing}")

    def test_install_registers_pretooluse_hook(self):
        self._run_install()
        settings = self.project / ".claude" / "settings.json"
        self.assertTrue(settings.exists(), "settings.json not written")
        data = json.loads(settings.read_text())
        hooks = data.get("hooks", {}).get("PreToolUse", [])
        self.assertTrue(
            any("axiom-csc" in e.get("hooks", [{}])[0].get("command", "") for e in hooks),
            f"PreToolUse hook missing from settings.json: {data}",
        )

    def test_install_generates_invariants_yaml(self):
        self._run_install()
        inv = self.project / ".axiom" / "invariants.yaml"
        self.assertTrue(inv.exists(), ".axiom/invariants.yaml not generated")
        text = inv.read_text()
        self.assertIn("concept:", text, "generated yaml must contain `concept:` rules")


if __name__ == "__main__":
    unittest.main()
